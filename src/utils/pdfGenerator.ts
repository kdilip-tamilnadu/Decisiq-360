import { jsPDF } from 'jspdf';
import html2canvas from 'html2canvas';
import { ModuleType, Finding } from '../types/index.ts';
import { formatCurrency, formatPercent } from './decimal.ts';

export interface PDFReportOptions {
  module: ModuleType | 'executive';
  runId: string;
  dataPayload: any;
  captureElement?: HTMLElement | null;
}

/**
 * Generates and downloads a stakeholder-ready PDF report for Decisiq 360
 */
export async function generateStakeholderPDFReport({
  module,
  runId,
  dataPayload,
  captureElement,
}: PDFReportOptions): Promise<void> {
  // If an element is provided, use html2canvas + jsPDF for exact visual fidelity
  if (captureElement) {
    const canvas = await html2canvas(captureElement, {
      scale: 2,
      useCORS: true,
      logging: false,
      backgroundColor: '#09090b', // obsidian background
    });

    const imgData = canvas.toDataURL('image/png');
    const pdf = new jsPDF({
      orientation: 'portrait',
      unit: 'mm',
      format: 'a4',
    });

    const imgWidth = 210; // A4 width mm
    const pageHeight = 297; // A4 height mm
    const imgHeight = (canvas.height * imgWidth) / canvas.width;
    let heightLeft = imgHeight;
    let position = 0;

    pdf.addImage(imgData, 'PNG', 0, position, imgWidth, imgHeight);
    heightLeft -= pageHeight;

    while (heightLeft > 0) {
      position = heightLeft - imgHeight;
      pdf.addPage();
      pdf.addImage(imgData, 'PNG', 0, position, imgWidth, imgHeight);
      heightLeft -= pageHeight;
    }

    const filename = `Decisiq360_${module.toUpperCase()}_Report_${runId.substring(0, 8)}.pdf`;
    pdf.save(filename);
    return;
  }

  // Native jsPDF vector report generator (works completely offline, lightweight, scalable)
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'pt',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 40;
  const contentWidth = pageWidth - margin * 2;
  let y = margin;

  // 1. Top Brand Banner
  doc.setFillColor(15, 15, 18); // Dark background header
  doc.rect(0, 0, pageWidth, 80, 'F');

  // Orange accent bar
  doc.setFillColor(249, 115, 22);
  doc.rect(0, 77, pageWidth, 3, 'F');

  // Logo Icon
  doc.setFillColor(249, 115, 22);
  doc.roundedRect(margin, 22, 34, 34, 6, 6, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.text('360', margin + 6, 44);

  // Brand Name
  doc.setFontSize(18);
  doc.text('Decisiq 360', margin + 44, 38);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(251, 146, 60); // light orange
  doc.text('360° Decision Intelligence for Financial Operations', margin + 44, 50);

  // Header Right Metadata
  doc.setFontSize(8);
  doc.setFont('courier', 'normal');
  doc.setTextColor(160, 160, 165);
  doc.text(`REPORT: ${module.toUpperCase()}`, pageWidth - margin, 32, { align: 'right' });
  doc.text(`RUN: ${runId}`, pageWidth - margin, 44, { align: 'right' });
  doc.text(`DATE: ${new Date().toLocaleDateString()} ${new Date().toLocaleTimeString()}`, pageWidth - margin, 56, {
    align: 'right',
  });

  y = 105;

  // 2. Executive Title & Confidentiality Notice
  doc.setTextColor(24, 24, 27);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  const moduleTitles: Record<string, string> = {
    reconciliation: 'Reconciliation Intelligence Audit Report',
    decision: 'Credit Decisioning & Policy Compliance Report',
    risk: 'Treasury Risk & Exposure Analysis Report',
    close: 'Month-End Financial Close Schedule Report',
    executive: 'Executive Decision Control Room Dossier',
  };
  doc.text(moduleTitles[module] || 'Financial Decision Intelligence Report', margin, y);
  y += 18;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(113, 113, 122);
  doc.text(
    'STAKEHOLDER NOTICE: Deterministic financial intelligence generated by Decisiq 360. All figures verified from actual source evidence.',
    margin,
    y
  );
  y += 24;

  // 3. KPI Summary Metric Grid
  doc.setFillColor(244, 244, 245);
  doc.roundedRect(margin, y, contentWidth, 58, 4, 4, 'F');
  doc.setDrawColor(228, 228, 231);
  doc.roundedRect(margin, y, contentWidth, 58, 4, 4, 'S');

  const stats = extractModuleStats(module, dataPayload);
  const colWidth = contentWidth / Math.max(1, stats.length);

  stats.forEach((st, idx) => {
    const colX = margin + idx * colWidth + 12;
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7.5);
    doc.setTextColor(113, 113, 122);
    doc.text(st.label.toUpperCase(), colX, y + 18);

    doc.setFontSize(13);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(24, 24, 27);
    doc.text(st.value, colX, y + 36);

    doc.setFontSize(7.5);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(st.highlightColor === 'orange' ? 234 : 113, st.highlightColor === 'orange' ? 88 : 113, st.highlightColor === 'orange' ? 12 : 122);
    doc.text(st.sub, colX, y + 48);
  });

  y += 76;

  // 4. Material Exceptions & Findings Table
  const findings: Finding[] = dataPayload.findings || [];
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(24, 24, 27);
  doc.text(`Material Exceptions & Audit Findings (${findings.length})`, margin, y);
  y += 14;

  // Table Header
  doc.setFillColor(24, 24, 27);
  doc.rect(margin, y, contentWidth, 20, 'F');
  doc.setFontSize(8);
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.text('SEVERITY', margin + 8, y + 13);
  doc.text('EXCEPTION TITLE & DESCRIPTION', margin + 70, y + 13);
  doc.text('IMPACT / CURRENCY', margin + 350, y + 13);
  doc.text('STATUS', margin + 460, y + 13);
  y += 20;

  if (findings.length === 0) {
    doc.setFillColor(250, 250, 250);
    doc.rect(margin, y, contentWidth, 24, 'F');
    doc.setTextColor(113, 113, 122);
    doc.setFont('helvetica', 'italic');
    doc.setFontSize(8);
    doc.text('No material exceptions or breaches detected. All entries satisfied policy thresholds.', margin + 12, y + 15);
    y += 28;
  } else {
    findings.slice(0, 10).forEach((f, idx) => {
      // Check page overflow
      if (y > pageHeight - 80) {
        doc.addPage();
        y = margin;
      }

      doc.setFillColor(idx % 2 === 0 ? 255 : 250, idx % 2 === 0 ? 255 : 250, idx % 2 === 0 ? 255 : 250);
      doc.rect(margin, y, contentWidth, 32, 'F');
      doc.setDrawColor(240, 240, 242);
      doc.line(margin, y + 32, margin + contentWidth, y + 32);

      // Severity badge
      if (f.severity === 'critical') {
        doc.setFillColor(254, 226, 226);
        doc.roundedRect(margin + 6, y + 8, 52, 14, 2, 2, 'F');
        doc.setTextColor(185, 28, 28);
      } else if (f.severity === 'high') {
        doc.setFillColor(254, 243, 199);
        doc.roundedRect(margin + 6, y + 8, 52, 14, 2, 2, 'F');
        doc.setTextColor(180, 83, 9);
      } else {
        doc.setFillColor(224, 242, 254);
        doc.roundedRect(margin + 6, y + 8, 52, 14, 2, 2, 'F');
        doc.setTextColor(3, 105, 161);
      }
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(7);
      doc.text(f.severity.toUpperCase(), margin + 12, y + 18);

      // Title & snippet
      doc.setTextColor(24, 24, 27);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8);
      doc.text(doc.splitTextToSize(f.title, 270)[0], margin + 70, y + 14);

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(7);
      doc.setTextColor(113, 113, 122);
      const descSnippet = f.description.length > 70 ? f.description.substring(0, 68) + '...' : f.description;
      doc.text(descSnippet, margin + 70, y + 25);

      // Impact
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8);
      doc.setTextColor(24, 24, 27);
      doc.text(f.impactAmount ? formatCurrency(f.impactAmount, f.currency || 'USD') : 'N/A', margin + 350, y + 18);

      // Status
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(7.5);
      doc.setTextColor(f.reviewStatus === 'approved' ? 22 : f.reviewStatus === 'flagged' ? 217 : 113, f.reviewStatus === 'approved' ? 101 : f.reviewStatus === 'flagged' ? 119 : 113, f.reviewStatus === 'approved' ? 52 : f.reviewStatus === 'flagged' ? 6 : 122);
      doc.text(f.reviewStatus.toUpperCase(), margin + 460, y + 18);

      y += 32;
    });
  }

  y += 16;

  // 5. Detailed Records Sample
  if (y < pageHeight - 120) {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.setTextColor(24, 24, 27);
    doc.text('Key Analyzed Items & Record Proof', margin, y);
    y += 12;

    doc.setFillColor(244, 244, 245);
    doc.rect(margin, y, contentWidth, 18, 'F');
    doc.setFontSize(7.5);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(113, 113, 122);

    if (module === 'reconciliation' && dataPayload.matches) {
      doc.text('RECORD A', margin + 8, y + 12);
      doc.text('RECORD B', margin + 160, y + 12);
      doc.text('VARIANCE', margin + 320, y + 12);
      doc.text('MATCH STATUS', margin + 420, y + 12);
      y += 18;

      dataPayload.matches.slice(0, 5).forEach((m: any, i: number) => {
        doc.setFillColor(i % 2 === 0 ? 255 : 250, i % 2 === 0 ? 255 : 250, i % 2 === 0 ? 255 : 250);
        doc.rect(margin, y, contentWidth, 18, 'F');
        doc.setFont('courier', 'normal');
        doc.setFontSize(7);
        doc.setTextColor(24, 24, 27);
        doc.text(`${m.recordA ? m.recordA.reference || m.recordA.transactionId : 'N/A'} ($${m.recordA?.amount.toFixed(2) || '0'})`, margin + 8, y + 12);
        doc.text(`${m.recordB ? m.recordB.reference || m.recordB.transactionId : 'N/A'} ($${m.recordB?.amount.toFixed(2) || '0'})`, margin + 160, y + 12);
        doc.text(m.amountDifference > 0.001 ? `+$${m.amountDifference.toFixed(2)}` : '$0.00', margin + 320, y + 12);
        doc.text(m.status.toUpperCase(), margin + 420, y + 12);
        y += 18;
      });
    } else if (module === 'decision' && dataPayload.evaluations) {
      doc.text('APP ID & BORROWER', margin + 8, y + 12);
      doc.text('REQUESTED', margin + 160, y + 12);
      doc.text('DTI / FICO', margin + 260, y + 12);
      doc.text('RECORDED vs COMPUTED', margin + 360, y + 12);
      y += 18;

      dataPayload.evaluations.slice(0, 5).forEach((ev: any, i: number) => {
        doc.setFillColor(i % 2 === 0 ? 255 : 250, i % 2 === 0 ? 255 : 250, i % 2 === 0 ? 255 : 250);
        doc.rect(margin, y, contentWidth, 18, 'F');
        doc.setFont('courier', 'normal');
        doc.setFontSize(7);
        doc.setTextColor(24, 24, 27);
        doc.text(`${ev.application.id} - ${ev.application.applicantName}`, margin + 8, y + 12);
        doc.text(`$${ev.application.requestedAmount.toLocaleString()}`, margin + 160, y + 12);
        doc.text(`${ev.computedDTI.toFixed(1)}% / ${ev.application.creditScore}`, margin + 260, y + 12);
        doc.text(`${ev.application.recordedOutcome} -> ${ev.computedOutcome}`, margin + 360, y + 12);
        y += 18;
      });
    } else if (module === 'risk' && dataPayload.topConcentrations) {
      doc.text('COUNTERPARTY', margin + 8, y + 12);
      doc.text('GROSS EXPOSURE', margin + 180, y + 12);
      doc.text('PORTFOLIO SHARE', margin + 320, y + 12);
      doc.text('LIMIT STATUS', margin + 420, y + 12);
      y += 18;

      dataPayload.topConcentrations.slice(0, 5).forEach((cp: any, i: number) => {
        doc.setFillColor(i % 2 === 0 ? 255 : 250, i % 2 === 0 ? 255 : 250, i % 2 === 0 ? 255 : 250);
        doc.rect(margin, y, contentWidth, 18, 'F');
        doc.setFont('courier', 'normal');
        doc.setFontSize(7);
        doc.setTextColor(24, 24, 27);
        doc.text(cp.counterparty, margin + 8, y + 12);
        doc.text(`$${cp.grossExposure.toLocaleString()}`, margin + 180, y + 12);
        doc.text(`${cp.shareOfTotalPercent}%`, margin + 320, y + 12);
        doc.text(cp.isBreached ? 'BREACH' : 'NORMAL', margin + 420, y + 12);
        y += 18;
      });
    } else if (module === 'close' && dataPayload.tasks) {
      doc.text('TASK NAME', margin + 8, y + 12);
      doc.text('OWNER', margin + 220, y + 12);
      doc.text('DURATION', margin + 330, y + 12);
      doc.text('SCHEDULE & SLACK', margin + 420, y + 12);
      y += 18;

      dataPayload.tasks.slice(0, 5).forEach((t: any, i: number) => {
        doc.setFillColor(i % 2 === 0 ? 255 : 250, i % 2 === 0 ? 255 : 250, i % 2 === 0 ? 255 : 250);
        doc.rect(margin, y, contentWidth, 18, 'F');
        doc.setFont('courier', 'normal');
        doc.setFontSize(7);
        doc.setTextColor(24, 24, 27);
        doc.text(t.name, margin + 8, y + 12);
        doc.text(t.owner, margin + 220, y + 12);
        doc.text(`${t.durationHours} hrs`, margin + 330, y + 12);
        doc.text(`Slack: ${t.slack || 0}h ${t.isCritical ? '(CRITICAL)' : ''}`, margin + 420, y + 12);
        y += 18;
      });
    }
  }

  // Footer on page
  const pageCount = (doc.internal as any).getNumberOfPages ? (doc.internal as any).getNumberOfPages() : 1;
  for (let p = 1; p <= pageCount; p++) {
    doc.setPage(p);
    doc.setDrawColor(228, 228, 231);
    doc.line(margin, pageHeight - 32, pageWidth - margin, pageHeight - 32);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(161, 161, 170);
    doc.text('Decisiq 360 Financial Decision Intelligence Platform • 100% Offline-First Architecture', margin, pageHeight - 20);
    doc.text(`Page ${p} of ${pageCount}`, pageWidth - margin, pageHeight - 20, { align: 'right' });
  }

  const filename = `Decisiq360_${module.toUpperCase()}_Report_${runId.substring(0, 8)}.pdf`;
  doc.save(filename);
}

function extractModuleStats(
  module: ModuleType | 'executive',
  data: any
): { label: string; value: string; sub: string; highlightColor?: string }[] {
  if (module === 'reconciliation') {
    return [
      {
        label: 'Reconciliation Rate',
        value: `${formatPercent(data.reconciliationRatePercent || 0, 1)}`,
        sub: `${data.matchedCount || 0} matched items`,
        highlightColor: 'orange',
      },
      {
        label: 'Matched Volume',
        value: formatCurrency(data.matchedVolume || 0),
        sub: 'Validated 1-to-1',
      },
      {
        label: 'Discrepancies',
        value: String(data.discrepancyCount || 0),
        sub: 'Within tolerance',
        highlightColor: (data.discrepancyCount || 0) > 0 ? 'orange' : undefined,
      },
      {
        label: 'Unmatched A / B',
        value: `${data.unmatchedACount || 0} / ${data.unmatchedBCount || 0}`,
        sub: formatCurrency(data.netResidualAmount || 0),
      },
    ];
  }

  if (module === 'decision') {
    return [
      {
        label: 'Total Applications',
        value: String(data.totalApplications || 0),
        sub: 'Audited batch',
      },
      {
        label: 'Policy Conflicts',
        value: String(data.conflictingDecisionsCount || 0),
        sub: 'Recorded != Computed',
        highlightColor: (data.conflictingDecisionsCount || 0) > 0 ? 'orange' : undefined,
      },
      {
        label: 'Computed Passes',
        value: String(data.computedPasses || 0),
        sub: 'Conformed to policy',
      },
      {
        label: 'Computed Declines',
        value: String(data.computedFails || 0),
        sub: 'Breached rules',
      },
    ];
  }

  if (module === 'risk') {
    return [
      {
        label: 'Total Gross Exposure',
        value: formatCurrency(data.totalGrossExposure || 0),
        sub: `${data.positionsCount || 0} positions`,
      },
      {
        label: 'Net Exposure',
        value: formatCurrency(data.totalNetExposure || 0),
        sub: 'After collateral',
      },
      {
        label: 'Limit Breaches',
        value: String(data.activeBreachesCount || 0),
        sub: (data.activeBreachesCount || 0) > 0 ? 'Critical action req.' : 'No breaches',
        highlightColor: (data.activeBreachesCount || 0) > 0 ? 'orange' : undefined,
      },
      {
        label: 'Top Concentration',
        value: `${data.topConcentrations?.[0]?.shareOfTotalPercent || 0}%`,
        sub: data.topConcentrations?.[0]?.counterparty || 'None',
      },
    ];
  }

  if (module === 'close') {
    return [
      {
        label: 'Completion Rate',
        value: `${formatPercent(data.completionRatePercent || 0, 1)}`,
        sub: `${data.completedTasks || 0} of ${data.totalTasks || 0} tasks`,
      },
      {
        label: 'Critical Path',
        value: `${data.totalProjectDurationHours || 0} hrs`,
        sub: 'Earliest finish cycle',
        highlightColor: 'orange',
      },
      {
        label: 'Active Blockers',
        value: String(data.blockers?.length || 0),
        sub: `${data.blockers?.filter((b: any) => b.isCriticalPath)?.length || 0} on critical path`,
      },
      {
        label: 'Task State',
        value: `${data.inProgressTasks || 0} In Prog`,
        sub: `${data.notStartedTasks || 0} Not Started`,
      },
    ];
  }

  return [
    {
      label: 'Completed Engines',
      value: `${data.briefing?.completedModulesCount || 0} / 4`,
      sub: 'Active departments',
      highlightColor: 'orange',
    },
    {
      label: 'Unresolved Exceptions',
      value: String(data.briefing?.unresolvedCriticalFindings?.length || 0),
      sub: 'Pending sign-off',
    },
    {
      label: 'Total Variance',
      value: formatCurrency(data.briefing?.totalUnresolvedDiscrepancyAmount || 0),
      sub: 'Material exposure',
    },
  ];
}
